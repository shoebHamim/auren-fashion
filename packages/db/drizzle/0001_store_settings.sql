CREATE TABLE "store_settings" (
	"id" smallint PRIMARY KEY DEFAULT 1 NOT NULL,
	"store_name" text DEFAULT 'Auren' NOT NULL,
	"legal_name" text,
	"tax_registration_id" text,
	"address" jsonb,
	"email" text,
	"phone" text,
	"currency" char(3) DEFAULT 'USD' NOT NULL,
	"currency_exponent" smallint DEFAULT 2 NOT NULL,
	"timezone" text DEFAULT 'UTC' NOT NULL,
	"order_number_prefix" text DEFAULT 'AU' NOT NULL,
	"return_window_days" integer DEFAULT 14 NOT NULL,
	"low_stock_default" integer DEFAULT 3 NOT NULL,
	"payment_hold_minutes" integer DEFAULT 30 NOT NULL,
	"unpaid_order_cancel_hours" integer DEFAULT 24 NOT NULL,
	"cod_enabled" boolean DEFAULT true NOT NULL,
	"cod_max_order_amount" bigint,
	"cod_requires_review" boolean DEFAULT false NOT NULL,
	"version" integer DEFAULT 1 NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "store_settings_singleton" CHECK ("store_settings"."id" = 1),
	CONSTRAINT "store_settings_currency_exponent" CHECK ("store_settings"."currency_exponent" BETWEEN 0 AND 4),
	CONSTRAINT "store_settings_cod_max_positive" CHECK ("store_settings"."cod_max_order_amount" IS NULL OR "store_settings"."cod_max_order_amount" > 0),
	CONSTRAINT "store_settings_positive_windows" CHECK ("store_settings"."return_window_days" >= 0 AND "store_settings"."low_stock_default" >= 0 AND "store_settings"."payment_hold_minutes" > 0 AND "store_settings"."unpaid_order_cancel_hours" > 0)
);
